from mcp.server.mcpserver import MCPServer
from mcp.server.mcpserver.exceptions import ToolError

from ta_mcp.utils import find_submission_path, save_report, unarchive_submission

logger = logging.getLogger("ta_mcp.grader")

mcp = MCPServer("GraderServer")


@mcp.tool(
    title="Get Submission Contents",
    description="Extract and pack the contents of a submission archive into a single string.",
)
def get_submission(submission_idx: str) -> str:
    """Extract and pack the contents of a submission archive into a single string.

    Args:
        submission_idx: The identifier of the submission.

    Returns:
        A formatted string containing the names and contents of all files.
    """
    packed_content = []

    with tempfile.TemporaryDirectory() as temp_dir:
        unarchive_submission(submission_idx, Path(temp_dir))

        extracted_path = Path(temp_dir)
        for file_path in extracted_path.rglob("*"):
            if not file_path.is_file():
                continue

            relative_path = file_path.relative_to(extracted_path)
            packed_content.append(f"--- File: {relative_path} ---")
            try:
                packed_content.append(file_path.read_text(encoding="utf-8"))
            except UnicodeDecodeError:
                packed_content.append("<binary or non-UTF-8 content>")

    return "\n".join(packed_content)


@mcp.tool(
    title="Run Clang-Tidy Analysis",
    description="Run clang-tidy analysis on the extracted source files of a submission.",
)
def check_clang_tidy(submission_idx: str) -> str:
    """Run clang-tidy analysis on the extracted source files of a submission.

    Args:
        submission_idx: The identifier of the submission.

    Returns:
        The console output generated by the clang-tidy command.
    """
    logger.info("Running clang-tidy for submission %s", submission_idx)

    with tempfile.TemporaryDirectory() as temp_dir:
        unarchive_submission(submission_idx, Path(temp_dir))

        extracted_path = Path(temp_dir)
        source_files = []
        for extension in (".c", ".cpp", ".cxx", ".cc", ".h", ".hpp"):
            source_files.extend(list(extracted_path.rglob(f"*{extension}")))

        if not source_files:
            return "Error: No C/C++ files found in submission"

        command_args = (
            ["clang-tidy"] + [str(path.resolve()) for path in source_files] + ["--"]
        )
        logger.info("Executing clang-tidy for submission %s", submission_idx)

        process_result = subprocess.run(
            command_args,
            cwd=temp_dir,
            capture_output=True,
            text=True,
            check=False,
        )

        combined_output = process_result.stdout
        if process_result.stderr:
            combined_output += "\n" + process_result.stderr

        if not combined_output.strip():
            return "Success: clang-tidy passed with no warnings"
        return combined_output


